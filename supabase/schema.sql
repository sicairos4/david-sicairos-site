-- 209 Adaptation Feed schema
create table if not exists adaptation_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  trigger text not null,
  observation text not null,
  decision text not null,
  action text not null,
  status text default 'Applied',
  platform text,
  post_url text
);
create table if not exists top_posts_48h (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  title text not null,
  platform text not null,
  engagement_delta numeric,
  reason text,
  url text
);
alter table adaptation_log enable row level security;
alter table top_posts_48h enable row level security;
create policy "public read adaptation_log" on adaptation_log for select using (true);
create policy "public read top_posts_48h" on top_posts_48h for select using (true);